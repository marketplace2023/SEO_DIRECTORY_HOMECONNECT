// Meaning determines the mode; an inspection is never maintenance by position.
export function serviceMode(name: Localized): Service["mode"] {
  const text = name.en.toLowerCase();
  if (/inspect|diagnos|assessment|detection|reinspection/.test(text))
    return "assessment";
  if (/design|planning|selection|coordination/.test(text)) return "design";
  if (/clean|wash|removal|pumping|clear-out|dismantl|grinding/.test(text))
    return "cleaning";
  if (
    /repair|restoration|adjustment|rekey|refacing|sealing|refinish|treatment|control|unlock|follow-up/.test(
      text,
    )
  )
    return "repair";
  if (/maintenance|care|tune-up|prun|scheduling/.test(text))
    return "maintenance";
  return "installation";
}
